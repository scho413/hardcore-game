/** 행 길이가 16이 아니면 잘라내거나 투명으로 채움 */
export function normalizedRows(sprite: PixelSprite, size = 16): string[] {
  return sprite.rows.map((r) => (r.length >= size ? r.slice(0, size) : r.padEnd(size, '.')));
}
